class LLMOrchestrator:
    """Intelligent reasoning and action orchestration layer powered by Gemini 3.8 Flash."""

    def __init__(self):
        self.api_key = os.getenv("GEMINI_API_KEY")
        self.client = None
        if genai and self.api_key:
            try:
                self.client = genai.Client(api_key=self.api_key)
                logger.info("Initialized Google GenAI client for gemini-3.8-flash.")
            except Exception as exc:
                logger.warning(f"Failed to instantiate GenAI client: {exc}")
                self.client = None
        else:
            logger.warning("GEMINI_API_KEY not configured or google-genai missing; using template router.")

    def _build_system_prompt(self, memory_context: str) -> str:
        """Construct the system prompt detailing available MCP tools and guidelines."""
        tools_summary = []
        for tool in AVAILABLE_TOOLS:
            name = tool.get("name")
            desc = tool.get("description")
            props = tool.get("inputSchema", {}).get("properties", {})
            reqs = tool.get("inputSchema", {}).get("required", [])
            tools_summary.append(f"- Tool: `{name}` | Desc: {desc} | Required: {reqs} | Properties: {list(props.keys())}")

        return (
            "You are Alexa+, the advanced AI assistant running inside an Amazon Alexa Skill with MCP tools and persistent memory.\n"
            f"### RECENT USER PROFILE & HISTORICAL CONTEXT:\n{memory_context or 'No prior preferences recorded.'}\n\n"
            f"### AVAILABLE MCP TOOLS:\n" + "\n".join(tools_summary) + "\n\n"
            "### EXECUTION GUIDELINES:\n"
            "1. Deliver responses optimized for voice: crisp, natural, concise (1-3 sentences).\n"
            "2. When a booking, status check, automation, or query is requested, select matching MCP tool and supply arguments.\n"
            "3. If missing required arguments, set tool_call to null, ask for clarification in speech, and provide reprompt.\n"
            "4. Return ONLY a strictly valid JSON object matching this schema:\n"
            "{\n"
            '  "reasoning": "Brief thought process",\n'
            '  "speech": "Natural voice response for Alexa to speak",\n'
            '  "reprompt": "Optional reprompt if waiting for user, or null",\n'
            '  "tool_call": {"tool_name": "name_or_null", "arguments": {}},\n'
            '  "should_end_session": false\n'
            "}\n"
            "Do NOT include markdown fences (```json). Return raw JSON only."
        )

    def route_utterance(
        self,
        utterance: str,
        session_id: str,
        user_id: str,
        memory: MemoryEngine,
        intent_name: Optional[str] = None,
        slots: Optional[Dict[str, Any]] = None,
    ) -> LLMDecisionSchema:
        """Route user voice utterance through Gemini intelligence and execute MCP tools."""
        # 1. Zero-latency Fast Path (< 25ms) for ALL smart devices, bookings, tasks
        try:
            from services.agent_orchestrator import AgenticOrchestrator
            orch = AgenticOrchestrator(user_id=user_id)
            fast_res = orch._check_fast_path(utterance, utterance.lower().strip(), session_id)
            if fast_res:
                tool_name = fast_res.get("tool_used")
                memory.save_conversation_turn(session_id, "assistant", fast_res["response"], intent_name, tool_name)
                return LLMDecisionSchema(
                    reasoning=fast_res.get("thought", "Fast path automated execution"),
                    speech=fast_res["response"],
                    tool_call=ToolInvocationSchema(tool_name=tool_name, arguments={}) if tool_name else None,
                    should_end_session=False,
                )
        except Exception as fast_err:
            logger.warning(f"Fast path check in lambda handler skipped: {fast_err}")

        memory_summary = memory.build_context_summary()
        if self.client and should_search_google(utterance, intent_name):
            try:
                search_answer = google_search_answer(utterance, self.client)
                if search_answer:
                    memory.save_conversation_turn(
                        session_id,
                        "assistant",
                        search_answer,
                        intent_name,
                        "google_search",
                    )
                    return LLMDecisionSchema(
                        reasoning="Answered a general-knowledge question with Google Search grounding.",
                        speech=search_answer,
                    )
            except Exception as exc:
                logger.warning("Google Search grounding failed: %s", exc, exc_info=True)

        if not self.client:
            return self._fallback_orchestrator(utterance, intent_name, slots, session_id)

        system_instruction = self._build_system_prompt(memory_summary)
        prompt = (
            f"{system_instruction}\n\nUser Request:\n"
            f"Intent: {intent_name or 'AlexaPlusIntent'} | Slots: {json.dumps(slots or {})} | Utterance: \"{utterance}\"\n"
            "Determine the action and produce raw JSON response now:"
        )

        try:
            logger.info(f"Invoking Gemini for session {session_id}...")
            raw_text = ""
            try:
                response = self.client.models.generate_content(
                    model=os.getenv("GEMINI_MODEL", "gemini-3.5-flash-lite"),
                    contents=prompt
                )
                raw_text = getattr(response, "text", "") or ""
            except Exception:
                response = self.client.interactions.create(
                    model=os.getenv("GEMINI_SEARCH_MODEL", "gemini-3.5-flash-lite"),
                    input=prompt
                )
                raw_text = getattr(response, "output_text", "") or getattr(response, "text", "") or ""

            clean_json = raw_text.strip()
            if clean_json.startswith("```json"):
                clean_json = clean_json[7:]
            if clean_json.startswith("```"):
                clean_json = clean_json[3:]
            if clean_json.endswith("```"):
                clean_json = clean_json[:-3]
            clean_json = clean_json.strip()

            decision = LLMDecisionSchema.model_validate(json.loads(clean_json))

            if decision.tool_call and decision.tool_call.tool_name:
                tool_name = decision.tool_call.tool_name
                args = decision.tool_call.arguments or {}
                logger.info(f"Executing MCP tool '{tool_name}' decided by LLM...")
                try:
                    tool_result = call_tool(tool_name, args, session_id=session_id)
                    is_error = tool_result.get("isError", False)
                    memory.save_conversation_turn(session_id, "assistant", decision.speech, intent_name, tool_name)
                    if is_error:
                        decision.speech += " Note: The backend reported a minor issue completing the tool action."
                except Exception as tool_exc:
                    logger.error(f"Error executing MCP tool '{tool_name}': {tool_exc}")
                    decision.speech = f"I processed your request, but experienced an error calling {tool_name}."

            return decision

        except Exception as exc:
            logger.warning(f"LLM routing failed ({exc}); falling back to template router.")
            return self._fallback_orchestrator(utterance, intent_name, slots, session_id)

    def _fallback_orchestrator(
        self,
        utterance: str,
        intent_name: Optional[str],
        slots: Optional[Dict[str, Any]],
        session_id: str,
    ) -> LLMDecisionSchema:
        """Deterministic fallback router when LLM API is unavailable."""
        slots = slots or {}
        lowered = (utterance or "").lower()

        if intent_name == "CreateBookingIntent" or "book" in lowered or "reserve" in lowered:
            title = slots.get("booking_title") or "General Appointment"
            customer = slots.get("customer_name") or "Alexa User"
            category = slots.get("booking_category") or "general"
            sched_time = slots.get("booking_time") or datetime.now(timezone.utc).isoformat()
            try:
                call_tool("alexa_create_booking", {"title": title, "customer_name": customer, "category": category, "scheduled_time": sched_time}, session_id=session_id)
                return LLMDecisionSchema(
                    reasoning="Created booking via fallback.",
                    speech=f"I've successfully created your booking for {title} under {customer}.",
                    tool_call=ToolInvocationSchema(tool_name="alexa_create_booking", arguments={"title": title, "customer_name": customer}),
                    should_end_session=False,
                )
            except Exception as e:
                return LLMDecisionSchema(reasoning=str(e), speech="I encountered an error creating your booking.", should_end_session=False)

        if intent_name == "SmartHomeIntent" or "turn" in lowered or "light" in lowered:
            device = slots.get("device_name") or "living_room_lights"
            command = slots.get("action_command") or "toggle"
            try:
                call_tool("alexa_execute_automation", {"action_type": command, "target_device_or_service": device, "parameters": {}, "notify_user": False}, session_id=session_id)
                return LLMDecisionSchema(
                    reasoning="Executed smart home automation.",
                    speech=f"Done. I sent the {command} command to {device}.",
                    tool_call=ToolInvocationSchema(tool_name="alexa_execute_automation", arguments={"action_type": command, "target_device_or_service": device}),
                    should_end_session=False,
                )
            except Exception as e:
                return LLMDecisionSchema(reasoning=str(e), speech=f"Could not execute automation on {device}.", should_end_session=False)

        if intent_name == "CheckStatusIntent" or "status" in lowered or "task" in lowered:
            status_filter = slots.get("status_filter") or "all"
            try:
                call_tool("alexa_query_tasks", {"status": status_filter, "limit": 5})
                return LLMDecisionSchema(
                    reasoning="Queried tasks via fallback.",
                    speech=f"Checked tasks with status {status_filter}. Your active records are synchronized.",
                    should_end_session=False,
                )
            except Exception:
                return LLMDecisionSchema(reasoning="Query failed.", speech="Unable to retrieve current tasks right now.", should_end_session=False)

        if intent_name == "SystemHealthIntent" or "health" in lowered:
            try:
                call_tool("alexa_get_system_health", {})
                return LLMDecisionSchema(
                    reasoning="Checked health via fallback.",
                    speech="All Alexa+ MCP services and database connections are operational and healthy.",
                    should_end_session=False,
                )
            except Exception:
                return LLMDecisionSchema(reasoning="Health check failed.", speech="System health check indicates components are degraded.", should_end_session=False)

        return LLMDecisionSchema(
            reasoning="Default voice response.",
            speech="I am Alexa+, connected to your MCP backend and memory. You can ask me to book appointments, trigger automations, or check your schedule.",
            reprompt="What would you like me to do next?",
            should_end_session=False,
        )


orchestrator = LLMOrchestrator()


