def send_proactive_notification(user_id: str, message: str) -> bool:
    """Push an outbound proactive notification to an Alexa customer device."""
    client_id = os.getenv("ALEXA_CLIENT_ID")
    client_secret = os.getenv("ALEXA_CLIENT_SECRET")
    stage = os.getenv("ALEXA_STAGE", "development").lower()

    if not client_id or not client_secret:
        logger.info(f"[ProactiveNotification-Simulated] user={user_id} message='{message}'")
        return True

    token_url = "https://api.amazon.com/auth/O2/token"
    token_payload = {
        "grant_type": "client_credentials",
        "client_id": client_id,
        "client_secret": client_secret,
        "scope": "alexa::proactive_events",
    }
    try:
        token_res = requests.post(token_url, data=token_payload, timeout=5.0)
        token_res.raise_for_status()
        access_token = token_res.json().get("access_token")
    except Exception as exc:
        logger.error(f"Failed to obtain Proactive Events OAuth token: {exc}")
        return False

    api_endpoint = (
        "https://api.amazonalexa.com/v1/proactiveEvents/stages/development"
        if stage == "development"
        else "https://api.amazonalexa.com/v1/proactiveEvents/stages/live"
    )
    now = datetime.now(timezone.utc)
    expiry = datetime.fromtimestamp(now.timestamp() + 3600, tz=timezone.utc)

    event_payload = {
        "timestamp": now.strftime("%Y-%m-%dT%H:%M:%S.000Z"),
        "referenceId": str(uuid.uuid4()),
        "expiryTime": expiry.strftime("%Y-%m-%dT%H:%M:%S.000Z"),
        "event": {
            "name": "AMAZON.MessageAlert.Activated",
            "payload": {
                "state": {"status": "UNREAD", "freshness": "NEW"},
                "messageGroup": {"creator": {"name": "Alexa+ MCP Assistant"}, "count": 1, "urgency": "URGENT"},
            },
        },
        "relevantAudience": {
            "type": "Unicast" if user_id and user_id != "broadcast" else "Multicast",
            "payload": {"user": user_id} if user_id and user_id != "broadcast" else {},
        },
    }
    try:
        headers = {"Authorization": f"Bearer {access_token}", "Content-Type": "application/json"}
        res = requests.post(api_endpoint, json=event_payload, headers=headers, timeout=5.0)
        res.raise_for_status()
        logger.info(f"Proactive notification published successfully to {user_id}")
        return True
    except Exception as exc:
        logger.error(f"Failed to dispatch proactive event to Alexa API: {exc}")
        return False


