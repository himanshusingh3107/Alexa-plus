class LaunchRequestHandler(AbstractRequestHandler):
    """Handler for Skill Launch: Welcome user, initialize memory profile, and prompt."""
    def can_handle(self, handler_input: HandlerInput) -> bool:
        return is_request_type("LaunchRequest")(handler_input)

    def handle(self, handler_input: HandlerInput) -> Response:
        session_id, user_id = get_session_and_user_identifiers(handler_input)
        memory = MemoryEngine(user_id=user_id)
        profile = memory.get_or_create_profile()
        preferred_name = profile.get("preferences", {}).get("preferred_name", "")
        greeting = f"Welcome back, {preferred_name}!" if preferred_name else "Welcome to Alexa+!"
        speech = f"{greeting} Your MCP intelligence engine is active. You can manage bookings, query tasks, or trigger smart devices."
        reprompt = "What can I help you coordinate today?"

        memory.save_conversation_turn(session_id=session_id, role="assistant", content=speech, intent_name="LaunchRequest")
        sync_session_turn(handler_input, "LaunchRequest", speech)
        return handler_input.response_builder.speak(speech).ask(reprompt).set_card(SimpleCard("Alexa+ MCP Active", speech)).response


