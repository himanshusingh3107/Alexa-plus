def get_session_and_user_identifiers(handler_input: HandlerInput) -> tuple:
    """Extract session_id and user_id safely from Alexa RequestEnvelope."""
    req_env = handler_input.request_envelope
    session = req_env.session
    session_id = session.session_id if session and session.session_id else f"sess-{uuid.uuid4()}"
    user_id = "default_alexa_user"
    if session and session.user and session.user.user_id:
        user_id = session.user.user_id
    elif req_env.context and req_env.context.system and req_env.context.system.user:
        user_id = req_env.context.system.user.user_id
    return session_id, user_id


def extract_slot_safe(handler_input: HandlerInput, slot_name: str) -> Optional[str]:
    """Retrieve slot value safely without raising exceptions."""
    try:
        val = get_slot_value(handler_input=handler_input, slot_name=slot_name)
        return str(val).strip() if val else None
    except Exception:
        return None


def sync_session_turn(handler_input: HandlerInput, intent_name: str, speech_text: str) -> None:
    """Update Alexa session attributes to preserve multi-turn context."""
    attr = handler_input.attributes_manager.session_attributes or {}
    attr["turn_count"] = attr.get("turn_count", 0) + 1
    attr["last_intent"] = intent_name
    attr["last_response_time"] = datetime.now(timezone.utc).isoformat()
    handler_input.attributes_manager.session_attributes = attr


def execute_voice_turn(
    handler_input: HandlerInput,
    intent_name: str,
    utterance: str,
    slots: Optional[Dict[str, Any]] = None,
    card_title: str = "Alexa+",
) -> Response:
    """Standardized handler logic: records memory turn, invokes LLM, updates session, and responds."""
    session_id, user_id = get_session_and_user_identifiers(handler_input)
    memory = MemoryEngine(user_id=user_id)
    memory.save_conversation_turn(session_id, "user", utterance, intent_name=intent_name)

    decision = orchestrator.route_utterance(
        utterance=utterance,
        session_id=session_id,
        user_id=user_id,
        memory=memory,
        intent_name=intent_name,
        slots=slots,
    )

    sync_session_turn(handler_input, intent_name, decision.speech)
    rb = handler_input.response_builder.speak(decision.speech)
    if decision.reprompt and not decision.should_end_session:
        rb.ask(decision.reprompt)
    rb.set_should_end_session(decision.should_end_session)
    rb.set_card(SimpleCard(card_title, decision.speech))
    return rb.response


