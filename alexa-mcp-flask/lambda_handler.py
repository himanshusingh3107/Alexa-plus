class ToolInvocationSchema(BaseModel):
    """Schema defining an MCP tool execution decided by the LLM."""
    tool_name: Optional[str] = Field(
        default=None,
        description="The specific MCP tool to invoke or None if no action required.",
    )
    arguments: Dict[str, Any] = Field(
        default_factory=dict,
        description="Dictionary of parameters matching the tool's input schema.",
    )


class LLMDecisionSchema(BaseModel):
    """Structured response schema generated by the Gemini LLM Orchestrator."""
    reasoning: str = Field(description="Analytical reasoning regarding user intent and tool selection.")
    speech: str = Field(description="The voice response to be spoken aloud by Alexa to the user.")
    reprompt: Optional[str] = Field(default=None, description="Optional reprompt if waiting for user input.")
    tool_call: Optional[ToolInvocationSchema] = Field(default=None, description="MCP tool invocation details.")
    should_end_session: bool = Field(default=False, description="Whether Alexa should conclude the voice session.")


